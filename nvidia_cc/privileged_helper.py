#!/usr/bin/env python3
"""
Privileged NVML, PCIe sysfs, & Kernel Module helper for NVIDIA Control Center on Linux.
Executed via pkexec (or systemd boot service) to apply hardware-level GPU tuning
and kernel-level parameters in a single batch.
"""

import argparse
import ctypes
import json
import os
from pathlib import Path
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from nvidia_cc.nvml_backend import (  # noqa: E402
    NVML_CLOCK_OFFSET_V1,
    _NvmlClockOffsetV1,
    _NvmlPciInfo,
)

NVML_CLOCK_GRAPHICS = 0
NVML_CLOCK_MEM = 2
NVML_PSTATE_0 = 0


def check_nvml(res, fn_name):
    if res != 0:
        raise RuntimeError(f"{fn_name} failed with NVML error code {res}")


def _set_clock_offset(nvml, dev, clock_type: int, offset_mhz: int) -> int:
    """Applies clock offset using modern nvmlDeviceSetClockOffsets with legacy VfOffset fallback."""
    if hasattr(nvml, "nvmlDeviceSetClockOffsets"):
        info = _NvmlClockOffsetV1()
        info.version = NVML_CLOCK_OFFSET_V1
        info.type = clock_type
        info.pstate = NVML_PSTATE_0
        info.clockOffsetMHz = int(offset_mhz)
        res = nvml.nvmlDeviceSetClockOffsets(dev, ctypes.byref(info))
        if res == 0:
            return 0
    if clock_type == NVML_CLOCK_GRAPHICS and hasattr(nvml, "nvmlDeviceSetGpcClkVfOffset"):
        return nvml.nvmlDeviceSetGpcClkVfOffset(dev, ctypes.c_int(int(offset_mhz)))
    if clock_type == NVML_CLOCK_MEM and hasattr(nvml, "nvmlDeviceSetMemClkVfOffset"):
        return nvml.nvmlDeviceSetMemClkVfOffset(dev, ctypes.c_int(int(offset_mhz)))
    return -1


def _install_system_integration(helper_path: Path, config_path: Path):
    """Installs Polkit passwordless rule for wheel group and systemd boot persistence service."""
    if os.geteuid() != 0:
        return

    helper_str = str(helper_path.resolve())
    polkit_rule = f"""// Auto-generated by NVIDIA Control Center (CachyOS)
polkit.addRule(function(action, subject) {{
    if (action.id == "org.freedesktop.policykit.exec" &&
        subject.isInGroup("wheel")) {{
        var cmd = action.lookup("command_line") || "";
        if (cmd.indexOf("privileged_helper.py") !== -1) {{
            return polkit.Result.YES;
        }}
    }}
}});
"""
    for rules_dir in [Path("/etc/polkit-1/rules.d"), Path("/usr/share/polkit-1/rules.d")]:
        try:
            if rules_dir.exists():
                rule_file = rules_dir / "90-nvidia-control-center.rules"
                if not rule_file.exists() or rule_file.read_text(encoding="utf-8", errors="ignore") != polkit_rule:
                    rule_file.write_text(polkit_rule, encoding="utf-8")
        except Exception:
            pass

    service_content = f"""[Unit]
Description=NVIDIA Control Center Hardware & Kernel Tuning Persistence
After=multi-user.target nvidia-persistenced.service
Wants=nvidia-persistenced.service

[Service]
Type=oneshot
ExecStart=/usr/bin/python3 {helper_str} --apply-config {config_path}
RemainAfterExit=yes

[Install]
WantedBy=multi-user.target
"""
    try:
        svc_file = Path("/etc/systemd/system/nvidia-cc-tuning.service")
        wrote_svc = False
        if not svc_file.exists() or svc_file.read_text(encoding="utf-8", errors="ignore") != service_content:
            svc_file.write_text(service_content, encoding="utf-8")
            wrote_svc = True
        if wrote_svc:
            subprocess.run(["systemctl", "daemon-reload"], check=False, timeout=5)
        subprocess.run(["systemctl", "enable", "nvidia-cc-tuning.service"], check=False, timeout=5)
    except Exception:
        pass


def _apply_kernel_settings(
    pci_bdf: str,
    pcie_pm: str | None,
    rebar: str | None,
    stream_memops: str | None,
    vrr_memclk: str | None,
    ntsync: str | None,
    applied: list[str],
    errors: list[str],
):
    if os.geteuid() != 0:
        return

    # 1. Runtime PCIe Power Management (sysfs + udev rule)
    if pcie_pm in ("on", "auto"):
        # Normalize 00000000:01:00.0 -> 0000:01:00.0
        bdf_norm = pci_bdf.lower()
        if bdf_norm.startswith("00000000:"):
            bdf_norm = bdf_norm[4:]
        sysfs_pm = Path(f"/sys/bus/pci/devices/{bdf_norm}/power/control")
        if not sysfs_pm.exists():
            # Fallback scan for NVIDIA VGA/3D controller
            for dev_dir in Path("/sys/bus/pci/devices").glob("*"):
                ven = dev_dir / "vendor"
                if ven.exists() and ven.read_text(encoding="utf-8", errors="ignore").strip() == "0x10de":
                    ctrl = dev_dir / "power" / "control"
                    if ctrl.exists():
                        sysfs_pm = ctrl
                        break
        try:
            if sysfs_pm.exists():
                sysfs_pm.write_text(f"{pcie_pm}\n", encoding="utf-8")
                applied.append(f"Kernel PCIe Power Control: {pcie_pm.upper()} ({sysfs_pm.parent.parent.name})")
        except Exception as exc:
            errors.append(f"PCIe PM sysfs write failed: {exc}")

        try:
            udev_file = Path("/etc/udev/rules.d/90-nvidia-control-center-pm.rules")
            udev_rule = (
                '# Auto-generated by NVIDIA Control Center (CachyOS)\n'
                f'ACTION=="add|bind", SUBSYSTEM=="pci", ATTR{{vendor}}=="0x10de", '
                f'ATTR{{class}}=="0x030000", ATTR{{power/control}}="{pcie_pm}"\n'
                f'ACTION=="add|bind", SUBSYSTEM=="pci", ATTR{{vendor}}=="0x10de", '
                f'ATTR{{class}}=="0x030200", ATTR{{power/control}}="{pcie_pm}"\n'
            )
            udev_file.write_text(udev_rule, encoding="utf-8")
        except Exception:
            pass

    # 2. Kernel Module Parameters (/etc/modprobe.d/90-nvidia-control-center.conf)
    if any(x is not None for x in (rebar, stream_memops, vrr_memclk)):
        rebar_val = 1 if rebar != "off" else 0
        smem_val = 1 if stream_memops != "off" else 0
        vrr_val = 1 if vrr_memclk == "on" else 0
        modprobe_conf = (
            "# Auto-generated by NVIDIA Control Center (CachyOS)\n"
            "options nvidia "
            "NVreg_InitializeSystemMemoryAllocations=0 "
            "NVreg_UsePageAttributeTable=1 "
            "NVreg_PreserveVideoMemoryAllocations=1 "
            "NVreg_TemporaryFilePath=/var/tmp "
            "NVreg_DynamicPowerManagement=3 "
            "NVreg_RestrictProfilingToAdminUsers=0 "
            f"NVreg_EnableResizableBar={rebar_val} "
            f"NVreg_EnableStreamMemOPs={smem_val} "
            f"NVreg_EnablePCIERelaxedOrderingMode={smem_val}\n"
            "options nvidia_drm modeset=1 fbdev=1\n"
            f"options nvidia_modeset hdmi_deepcolor=1 disable_vrr_memclk_switch={vrr_val}\n"
        )
        try:
            mp_path = Path("/etc/modprobe.d/90-nvidia-control-center.conf")
            mp_path.write_text(modprobe_conf, encoding="utf-8")
            applied.append(
                f"Kernel Modprobe Config (ReBAR={rebar_val}, StreamMemOPs={smem_val}, VRRMemLock={vrr_val})"
            )
        except Exception as exc:
            errors.append(f"Failed writing modprobe config: {exc}")

    # 3. Kernel Gaming Subsystem (ntsync module + sysctl vm.max_map_count & split_lock_mitigate)
    if ntsync is not None:
        try:
            ml_path = Path("/etc/modules-load.d/90-nvidia-control-center.conf")
            if ntsync == "on":
                ml_path.write_text("# Auto-generated by NVIDIA Control Center\nntsync\n", encoding="utf-8")
                subprocess.run(["modprobe", "ntsync"], check=False, timeout=5)
                applied.append("Kernel Module: ntsync loaded (/dev/ntsync)")
            else:
                if ml_path.exists():
                    ml_path.unlink()
        except Exception as exc:
            errors.append(f"Kernel ntsync setup failed: {exc}")

        try:
            sysctl_path = Path("/etc/sysctl.d/90-nvidia-control-center.conf")
            split_val = 0 if ntsync == "on" else 1
            sysctl_conf = (
                "# Auto-generated by NVIDIA Control Center (CachyOS)\n"
                "vm.max_map_count = 2147483642\n"
                f"kernel.split_lock_mitigate = {split_val}\n"
            )
            sysctl_path.write_text(sysctl_conf, encoding="utf-8")
            subprocess.run(["sysctl", "-w", "vm.max_map_count=2147483642"], check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            subprocess.run(["sysctl", "-w", f"kernel.split_lock_mitigate={split_val}"], check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            applied.append(f"Kernel Sysctl: split_lock_mitigate={split_val}, max_map_count=2147483642")
        except Exception as exc:
            errors.append(f"Sysctl tuning failed: {exc}")


def _apply_kernel_framegen_env(enabled: bool, applied: list[str], errors: list[str]):
    """Sets system-wide OptiScaler universal Frame Generation environment configs."""
    if os.geteuid() != 0:
        return
    try:
        env_d = Path("/etc/environment.d")
        env_d.mkdir(parents=True, exist_ok=True)
        conf_file = env_d / "90-nvidia-control-center.conf"
        prof_d = Path("/etc/profile.d")
        prof_d.mkdir(parents=True, exist_ok=True)
        sh_file = prof_d / "90-nvidia-control-center.sh"

        if enabled:
            fg_cfg = (
                "FrameGen.Enabled=true;"
                "FrameGen.FGInput=dlssg;"
                "FrameGen.FGOutput=fsrfg;"
                "FSRFG.AllowAsync=true;"
                "XeFG.InterpolationCount=1;"
                "Spoofing.StreamlineSpoofing=true;"
                "Spoofing.Dxgi=true;"
                "Spoofing.SpoofHAGS=true;"
                "Spoofing.SpoofedGPUName=NVIDIA GeForce RTX 4090;"
                "Spoofing.SpoofedDeviceId=0x2684;"
                "Spoofing.SpoofedVendorId=0x10de;"
                "Upscalers.Dx11Upscaler=dlss;"
                "Upscalers.Dx12Upscaler=dlss;"
                "Upscalers.VulkanUpscaler=dlss;"
                "DLSS.Enabled=true"
            )
            conf_content = (
                "# Auto-generated by NVIDIA Control Center (CachyOS)\n"
                "PROTON_USE_OPTISCALER=1\n"
                "WINEDLLOVERRIDES=dxgi=n,b\n"
                f"PROTON_OPTISCALER_CONFIG={fg_cfg}\n"
                "PROTON_ENABLE_NGX_UPDATER=1\n"
                "PROTON_DLSS_UPGRADE=1\n"
                "PROTON_FSR4_UPGRADE=0\n"
                "__NV_PRIME_RENDER_OFFLOAD=1\n"
                "__GLX_VENDOR_LIBRARY_NAME=nvidia\n"
                "__VK_LAYER_NV_optimus=NVIDIA_only\n"
            )
            conf_file.write_text(conf_content, encoding="utf-8")
            sh_content = (
                "#!/bin/sh\n"
                "# Auto-generated by NVIDIA Control Center (CachyOS)\n"
                "export PROTON_USE_OPTISCALER=1\n"
                'export WINEDLLOVERRIDES="dxgi=n,b"\n'
                f'export PROTON_OPTISCALER_CONFIG="{fg_cfg}"\n'
                "export PROTON_ENABLE_NGX_UPDATER=1\n"
                "export PROTON_DLSS_UPGRADE=1\n"
                "export PROTON_FSR4_UPGRADE=0\n"
                "export __NV_PRIME_RENDER_OFFLOAD=1\n"
                "export __GLX_VENDOR_LIBRARY_NAME=nvidia\n"
                "export __VK_LAYER_NV_optimus=NVIDIA_only\n"
            )
            sh_file.write_text(sh_content, encoding="utf-8")
            sh_file.chmod(0o755)
            applied.append("Kernel & System Env: OptiScaler Frame Generation (/etc/environment.d & /etc/profile.d)")
        else:
            if conf_file.exists():
                conf_file.unlink()
            if sh_file.exists():
                sh_file.unlink()
    except Exception as exc:
        errors.append(f"Failed setting system-wide OptiScaler environment: {exc}")


def _apply_cpu_governor(governor: str | None, applied: list[str], errors: list[str]):
    if not governor or os.geteuid() != 0:
        return
    count = 0
    for p in Path("/sys/devices/system/cpu").glob("cpu*/cpufreq/scaling_governor"):
        try:
            p.write_text(f"{governor}\n", encoding="utf-8")
            count += 1
        except Exception:
            pass
    for p in Path("/sys/devices/system/cpu").glob("cpufreq/policy*/scaling_governor"):
        try:
            p.write_text(f"{governor}\n", encoding="utf-8")
            count += 1
        except Exception:
            pass
    for p in Path("/sys/devices/system/cpu").glob("cpu*/power/energy_perf_bias"):
        try:
            p.write_text("performance\n", encoding="utf-8")
        except Exception:
            pass
    if count > 0:
        applied.append(f"CPU Frequency Governor: {governor.upper()} ({count} cores/policies)")


def main():
    parser = argparse.ArgumentParser(description="Apply NVIDIA GPU hardware & kernel tuning settings")
    parser.add_argument("--gpu-index", type=int, default=0, help="GPU index (default: 0)")
    parser.add_argument("--power-limit", type=float, help="Power limit in Watts (e.g., 70.0)")
    parser.add_argument("--core-offset", type=int, help="GPU core clock offset in MHz (e.g., 100)")
    parser.add_argument("--mem-offset", type=int, help="GPU memory clock offset in MHz (e.g., 200)")
    parser.add_argument("--fan-mode", choices=["auto", "manual"], help="Fan control policy")
    parser.add_argument("--fan-speed", type=int, help="Manual fan speed percentage (0-100)")
    parser.add_argument("--persistence", choices=["on", "off"], help="Persistence mode")
    parser.add_argument("--reset-locked-clocks", action="store_true", help="Reset locked GPU clocks to default")
    parser.add_argument("--pcie-pm", choices=["on", "auto"], help="PCIe runtime power management (on=Max Perf, auto=Save)")
    parser.add_argument("--kernel-rebar", choices=["on", "off"], help="Kernel NVreg_EnableResizableBar")
    parser.add_argument("--kernel-stream-memops", choices=["on", "off"], help="Kernel NVreg_EnableStreamMemOPs & RelaxedOrdering")
    parser.add_argument("--kernel-vrr-memclk", choices=["on", "off"], help="Kernel nvidia_modeset disable_vrr_memclk_switch")
    parser.add_argument("--kernel-ntsync", choices=["on", "off"], help="Load Linux kernel ntsync & disable split_lock_mitigate")
    parser.add_argument("--kernel-framegen", choices=["on", "off"], help="OptiScaler universal frame generation kernel tuning")
    parser.add_argument("--cpu-governor", choices=["performance", "powersave"], help="Set CPU scaling governor")
    parser.add_argument("--apply-config", type=str, help="Path to tuning_config.json to apply at boot or batch")

    args = parser.parse_args()

    # Determine user config path for systemd service registration
    sudo_user = os.environ.get("PKEXEC_UID") or os.environ.get("SUDO_UID")
    config_path = Path.home() / ".config" / "nvidia-control-center" / "tuning_config.json"
    if sudo_user:
        try:
            import pwd
            pw = pwd.getpwuid(int(sudo_user))
            config_path = Path(pw.pw_dir) / ".config" / "nvidia-control-center" / "tuning_config.json"
        except Exception:
            pass
    if args.apply_config:
        config_path = Path(args.apply_config)

    # Load from JSON config if --apply-config was provided
    if args.apply_config and config_path.exists():
        try:
            cfg = json.loads(config_path.read_text(encoding="utf-8"))
            last = cfg.get("last_applied", {})
            if args.power_limit is None and "power_limit" in last:
                args.power_limit = float(last["power_limit"])
            if args.core_offset is None and "core_offset" in last:
                args.core_offset = int(last["core_offset"])
            if args.mem_offset is None and "mem_offset" in last:
                args.mem_offset = int(last["mem_offset"])
            if args.fan_mode is None and "fan_mode" in last:
                args.fan_mode = str(last["fan_mode"])
            if args.fan_speed is None and last.get("fan_speed") is not None:
                args.fan_speed = int(last["fan_speed"])
            if args.persistence is None:
                args.persistence = "on" if cfg.get("persistence", True) else "off"
            if args.pcie_pm is None:
                args.pcie_pm = cfg.get("pcie_pm", "on")
            if args.kernel_rebar is None:
                args.kernel_rebar = "on" if cfg.get("kernel_rebar", True) else "off"
            if args.kernel_stream_memops is None:
                args.kernel_stream_memops = "on" if cfg.get("kernel_stream_memops", True) else "off"
            if args.kernel_vrr_memclk is None:
                args.kernel_vrr_memclk = "on" if cfg.get("kernel_vrr_memclk", False) else "off"
            if args.kernel_ntsync is None:
                args.kernel_ntsync = "on" if cfg.get("kernel_ntsync", True) else "off"
            if args.kernel_framegen is None:
                args.kernel_framegen = "on" if cfg.get("kernel_framegen", True) else "off"
        except Exception:
            pass

    if args.kernel_framegen == "on":
        if args.pcie_pm is None:
            args.pcie_pm = "on"
        if args.kernel_rebar is None:
            args.kernel_rebar = "on"
        if args.kernel_stream_memops is None:
            args.kernel_stream_memops = "on"
        if args.kernel_vrr_memclk is None:
            args.kernel_vrr_memclk = "on"
        if args.kernel_ntsync is None:
            args.kernel_ntsync = "on"

    _install_system_integration(Path(__file__), config_path)

    nvml = ctypes.CDLL("libnvidia-ml.so.1")
    check_nvml(nvml.nvmlInit_v2(), "nvmlInit_v2")

    errors = []
    applied = []
    pci_bdf = "0000:01:00.0"

    try:
        dev = ctypes.c_void_p()
        check_nvml(nvml.nvmlDeviceGetHandleByIndex_v2(args.gpu_index, ctypes.byref(dev)), "nvmlDeviceGetHandleByIndex_v2")

        pci = _NvmlPciInfo()
        if hasattr(nvml, "nvmlDeviceGetPciInfo_v3") and nvml.nvmlDeviceGetPciInfo_v3(dev, ctypes.byref(pci)) == 0:
            pci_bdf = pci.busId.decode("utf-8", errors="replace").strip()

        if args.persistence is not None:
            pm_val = 1 if args.persistence == "on" else 0
            res = nvml.nvmlDeviceSetPersistenceMode(dev, ctypes.c_uint(pm_val))
            if res != 0:
                subprocess.run(["nvidia-smi", "-i", str(args.gpu_index), "-pm", str(pm_val)], check=False)
            if args.persistence == "on":
                for svc in [
                    "nvidia-persistenced.service",
                    "nvidia-suspend.service",
                    "nvidia-hibernate.service",
                    "nvidia-resume.service",
                ]:
                    subprocess.run(["systemctl", "enable", svc], check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                subprocess.run(["systemctl", "start", "nvidia-persistenced.service"], check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            applied.append(f"Persistence Mode: {args.persistence.upper()}")

        if args.power_limit is not None:
            mw = int(round(args.power_limit * 1000))
            res = nvml.nvmlDeviceSetPowerManagementLimit(dev, ctypes.c_uint(mw))
            if res != 0:
                errors.append(f"Power limit ({args.power_limit:.1f}W) failed (NVML code {res})")
            else:
                applied.append(f"Power Limit: {args.power_limit:.1f} W")

        if args.core_offset is not None:
            res = _set_clock_offset(nvml, dev, NVML_CLOCK_GRAPHICS, args.core_offset)
            if res != 0:
                errors.append(f"Core clock offset ({args.core_offset:+d} MHz) failed (NVML code {res})")
            else:
                applied.append(f"Core Clock Offset: {args.core_offset:+d} MHz")

        if args.mem_offset is not None:
            res = _set_clock_offset(nvml, dev, NVML_CLOCK_MEM, args.mem_offset)
            if res != 0:
                errors.append(f"Memory clock offset ({args.mem_offset:+d} MHz) failed (NVML code {res})")
            else:
                applied.append(f"Memory Clock Offset: {args.mem_offset:+d} MHz")

        if args.reset_locked_clocks:
            if hasattr(nvml, "nvmlDeviceResetGpuLockedClocks"):
                res = nvml.nvmlDeviceResetGpuLockedClocks(dev)
                if res == 0:
                    applied.append("GPU Locked Clocks: Reset to dynamic")
                else:
                    errors.append(f"Reset locked clocks failed (NVML code {res})")

        if args.fan_mode is not None:
            num_fans = ctypes.c_uint(1)
            if hasattr(nvml, "nvmlDeviceGetNumFans"):
                nvml.nvmlDeviceGetNumFans(dev, ctypes.byref(num_fans))
            fan_count = max(1, num_fans.value)

            if args.fan_mode == "auto":
                # NVML_FAN_POLICY_TEMPERATURE_CONTINOUS_SW = 0
                for fan_idx in range(fan_count):
                    if hasattr(nvml, "nvmlDeviceSetFanControlPolicy"):
                        res = nvml.nvmlDeviceSetFanControlPolicy(dev, ctypes.c_uint(fan_idx), ctypes.c_uint(0))
                        if res != 0:
                            errors.append(f"Fan {fan_idx} auto policy failed (NVML code {res})")
                applied.append("Fan Mode: Automatic (Firmware Curve)")
            elif args.fan_mode == "manual" and args.fan_speed is not None:
                speed = max(0, min(100, args.fan_speed))
                for fan_idx in range(fan_count):
                    if hasattr(nvml, "nvmlDeviceSetFanControlPolicy"):
                        nvml.nvmlDeviceSetFanControlPolicy(dev, ctypes.c_uint(fan_idx), ctypes.c_uint(1))
                    if hasattr(nvml, "nvmlDeviceSetFanSpeed_v2"):
                        res = nvml.nvmlDeviceSetFanSpeed_v2(dev, ctypes.c_uint(fan_idx), ctypes.c_uint(speed))
                        if res != 0:
                            errors.append(f"Fan {fan_idx} speed {speed}% failed (NVML code {res})")
                applied.append(f"Fan Mode: Manual ({speed}%)")

        _apply_kernel_settings(
            pci_bdf=pci_bdf,
            pcie_pm=args.pcie_pm,
            rebar=args.kernel_rebar,
            stream_memops=args.kernel_stream_memops,
            vrr_memclk=args.kernel_vrr_memclk,
            ntsync=args.kernel_ntsync,
            applied=applied,
            errors=errors,
        )

        if args.kernel_framegen is not None:
            _apply_kernel_framegen_env(args.kernel_framegen == "on", applied, errors)

        _apply_cpu_governor(args.cpu_governor, applied, errors)

    finally:
        nvml.nvmlShutdown()

    if applied:
        print("Applied: " + ", ".join(applied))
    if errors:
        print("Errors: " + "; ".join(errors), file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
